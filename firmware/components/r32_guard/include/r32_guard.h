/* Сторож основного ПК: автономное пробуждение без участия контроллера.
 *
 * Зачем это нужно. Контроллер Remo32 работает на основном ПК, поэтому в
 * схеме есть провал: если этот ПК выключился сам — пропало электричество,
 * зависание, неудачная перезагрузка — то с телефона командовать некому.
 * Единственное устройство, способное помочь, должно действовать само.
 *
 * Что делает. Периодически пингует основной ПК. Если тот молчит дольше
 * grace-периода, плата отправляет magic packet, ждёт retry-паузу и, если
 * ПК так и не ответил, повторяет — но не более заданного числа раз.
 *
 * Чего НЕ делает. Не будит ПК, выключенный намеренно: перед плановым
 * выключением контроллер посылает плате «snooze», и на это время сторож
 * молчит. Без этого система дралась бы с собственным пользователем.
 */
#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "esp_err.h"
#include "r32_config.h"

typedef enum {
    R32_GUARD_DISABLED = 0, /* выключен в настройках */
    R32_GUARD_WATCHING,     /* ПК на связи, всё спокойно */
    R32_GUARD_MISSING,      /* ПК молчит, идёт отсчёт grace-периода */
    R32_GUARD_WAKING,       /* magic packet отправлен, ждём загрузки */
    R32_GUARD_GAVE_UP,      /* попытки исчерпаны, ждём возвращения ПК */
    R32_GUARD_SNOOZING,     /* выключение было плановым, не вмешиваемся */
} r32_guard_state_t;

typedef struct {
    r32_guard_state_t state;
    bool host_alive;
    int64_t last_seen_ms;      /* -1, если ПК ни разу не отвечал */
    int64_t snooze_until_ms;   /* 0 — сна нет */
    int attempts;              /* побудок в текущей серии */
    int total_wakes;           /* за всё время с последнего запуска платы */
} r32_guard_status_t;

/* Запускает фоновую задачу. Если сторож выключен в настройках, задача всё
 * равно создаётся: её можно включить командой без перезагрузки платы. */
esp_err_t r32_guard_start(r32_config_t *cfg);

/* Приостановить сторожа на указанное число минут (0 — отменить сон).
 * Так контроллер сообщает о плановом выключении ПК. */
void r32_guard_snooze(int minutes);

void r32_guard_get_status(r32_guard_status_t *out);

/* Человекочитаемое имя состояния для отчёта и логов. */
const char *r32_guard_state_name(r32_guard_state_t state);

/* Регистрирует консольную команду guard.
 *
 * Конфигурация передаётся сюда, а не берётся из r32_guard_start: команда
 * должна работать и на ненастроенной плате. Иначе первая же попытка
 * настроить сторожа до Wi-Fi роняла бы устройство по нулевому указателю. */
void r32_guard_register_console(r32_config_t *cfg);
