/* Кнопка на плате: одна физическая, две команды.
 *
 * На типовом ESP32-S3 DevKit кнопок две, но занять можно только одну.
 * Вторая (RST/EN) замкнута на вход сброса чипа физически — прошивка её
 * не видит и увидеть не может. Поэтому обе нужные команды разведены по
 * длительности нажатия одной кнопки BOOT.
 *
 * Осторожно: BOOT — загрузочный строп. Если держать её в момент сброса
 * или подачи питания, плата уйдёт в режим прошивки и работать не будет.
 * В обычной работе, после загрузки, вывод свободен и читается как вход.
 */
#pragma once

#include <stdbool.h>

#include "esp_err.h"

/* GPIO кнопки BOOT. Одинаков на всех известных платах ESP32-S3 DevKit;
 * кнопка замыкает вывод на землю, поэтому нажатию соответствует ноль. */
#define R32_BUTTON_GPIO 0

/* Что считать коротким, а что долгим нажатием. Три секунды выбраны так,
 * чтобы выключить сторожа было нельзя случайно: эта команда оставляет
 * компьютер без присмотра. */
#define R32_BUTTON_LONG_PRESS_MS 3000

typedef void (*r32_button_handler_t)(void);

/* Запускает опрос кнопки. Обработчики вызываются из отдельной задачи,
 * поэтому в них можно работать с сетью. NULL вместо обработчика means
 * «на это нажатие не реагировать». */
esp_err_t r32_button_start(r32_button_handler_t on_short, r32_button_handler_t on_long);
