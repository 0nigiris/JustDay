"""Болтовня без Claude: «привет», «как дела», «ты тут?» — ответ за доли секунды (пункт 22 плана).

Эти фразы — львиная доля голосовых ходов, и каждая уходила в облако: секунды ожидания и токены подписки ради
«хорошо, а у вас?». Здесь два уровня. Фразу узнаёт жёсткий список, а не модель: узнавать «это болтовня»
нейросетью на 0,6 млрд значит рано или поздно принять просьбу за «привет». Ответ же говорит крошечная местная
модель (`brain.tiny_model`), а если её нет или она ответила странно — готовая фраза из набора. Выходит так,
что серьёзное уходит выше при любом исходе: в список попадает только фраза целиком, без хвоста.

Осознанно НЕ в списке «ок», «ладно», «хорошо», «ага»: после вопроса Claude («запустить?») это «да», и
перехватить его здесь значило бы оставить его вопрос без ответа."""
from __future__ import annotations

import logging
import random
import re

from . import fastpath, localllm
from .i18n import t

log = logging.getLogger("justday")

KINDS = {
    "greet": re.compile(r"^(привет|привет привет|приветик|здравствуй|здравствуйте|здорово|хай|добрый (день|вечер)|"
                        r"hello|hi|hey)$"),
    "how": re.compile(r"^(как дела|как ты|как жизнь|как настроение|как поживаешь|как сам|как оно|че как|"
                      r"как у тебя дела|how are you)$"),
    "here": re.compile(r"^(ты тут|ты здесь|ты слышишь|ты меня слышишь|ты слышишь меня|ты на месте|ты жив|алло|"
                       r"are you there)$"),
    "bye": re.compile(r"^(пока|пока пока|до свидания|до встречи|доброй ночи|спокойной ночи|bye|goodbye)$"),
    "praise": re.compile(r"^(молодец|ты молодец|умница|ты умница|красавчик|ты лучший|круто|супер|класс|здорово)$"),
}

CANNED = {
    "greet": ["Привет!", "Здравствуйте.", "Привет, я здесь."],
    "how": ["Хорошо, спасибо. А у вас?", "Всё в порядке. Чем помочь?", "Отлично, работаю."],
    "here": ["Да, я тут.", "Слышу вас.", "На месте."],
    "bye": ["До встречи!", "Пока!", "Отдыхайте."],
    "praise": ["Спасибо, стараюсь.", "Приятно слышать.", "Рад стараться."],
}

# Примеры в самом запросе, а не в истории чата: localllm.chat берёт одну пару «система — человек», а 0,6 млрд
# параметров без примеров отвечали «Добрый день!» на «как дела» и «Счастья!» на «спокойной ночи».
PROMPT = """Ты — {name}, голосовой помощник на компьютере. Человек просто общается. Ответь ОДНОЙ короткой фразой
(до двенадцати слов) по-русски, тепло и без пафоса. Без эмодзи, без разметки, без списков. Ничего не обещай
сделать и ничего не выдумывай про себя или про мир: если не знаешь, ответь коротко и просто.
Отвечай на то, что сказано, а не на что-то похожее. Примеры:
Человек: привет → Привет! Чем помочь?
Человек: как дела → Хорошо, спасибо. А у вас?
Человек: ты тут → Да, я здесь.
Человек: спокойной ночи → Спокойной ночи!
Человек: ты молодец → Спасибо, стараюсь."""

# Что должно звучать в ответе каждого рода. Живая проверка показала: модель на 0,6 млрд отвечает «Спокойной ночи!»
# на «как жизнь» и «Привет!» на «ты тут». Ответ не по теме хуже любой готовой фразы, поэтому её слова — фильтр.
ON_TOPIC = {
    "greet": re.compile(r"привет|здравствуй|добр|здорово|рад вас"),
    "how": re.compile(r"хорошо|отлично|нормально|прекрасно|в порядке|неплохо|замечательно|работаю"),
    "here": re.compile(r"\bда\b|\bтут\b|здесь|слышу|на месте"),
    "bye": re.compile(r"пока|до встречи|до свидания|до скорого|ночи|отдых|увидимся"),
    "praise": re.compile(r"спасибо|приятно|рад|стараюсь|благодарю"),
}

MAX_CHARS = 140


def kind(text: str) -> str:
    """Род болтовни («greet», «how», …) или «» — это просьба, и она идёт дальше по обычной дороге."""
    q = fastpath._clean(text)
    for name, rx in KINDS.items():
        if rx.match(q):
            return name
    return ""


def _sane(answer: str, heard: str, what: str = "") -> str:
    """Ответ крошечной модели годится, только если это одна короткая русская фраза без мусора."""
    answer = re.sub(r"<think>.*?</think>", "", answer or "", flags=re.S).strip().strip('"«»')
    line = answer.splitlines()[0].strip() if answer else ""
    if not line or len(line) > MAX_CHARS or re.search(r"https?:|[`*#{}\[\]<>/]", line):
        return ""
    # Вопрос по-русски — ответ по-русски: 0,6 млрд параметров любят съехать на английский.
    if re.search(r"[а-яё]", heard.lower()) and not re.search(r"[а-яё]", line.lower()):
        return ""
    if what in ON_TOPIC and not ON_TOPIC[what].search(line.lower().replace("ё", "е")):
        return ""
    return line


def reply(what: str, text: str, cfg: dict) -> str:
    """Что сказать на болтовню рода `what`. Блокирующий вызов: зовут из потока."""
    model = str(cfg.get("brain", {}).get("tiny_model") or "").strip()
    if model:
        try:
            name = cfg.get("user", {}).get("assistant_name") or "Джарвис"
            got = localllm.chat(PROMPT.format(name=name), text, max_tokens=60, timeout=4, model=model,
                                keep_alive="1m")
            if line := _sane(got, text, what):
                return line
        except Exception as e:  # Ollama не запущен, модель не скачана, не успела — не беда, есть готовые
            log.info("chitchat: местная модель не ответила (%s)", type(e).__name__)
    return t(random.choice(CANNED[what]))
