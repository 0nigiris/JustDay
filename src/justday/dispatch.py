"""Какой моделью думать над этой просьбой.

Зачем. Самая быстрая и дешёвая модель справляется с девятью просьбами из десяти: «открой дискорд»,
«сделай тише», «какая погода». Держать на них сильную — всё равно что возить хлеб из магазина на
грузовике: доедет, но лимиты кончатся к обеду, и к настоящей работе подойти будет уже не с чем.
Поэтому по умолчанию работает лёгкая, а сильная берётся тогда, когда задача того стоит.

Кто решает. Решает модель, а не список слов. Список слов выглядит надёжным ровно до первой просьбы,
которой в нём нет, — а таких просьб бесконечно много, и человек не обязан знать, какие слова мы
считаем важными. Поэтому судит **местная** модель: она крутится на той же видеокарте, стоит ноль и
отвечает за полсекунды. Правила остаются, но только как запасной путь, когда местной модели нет.

Чего здесь нарочно нет: самой работы. Этот модуль только отвечает «лёгкой» или «сильной», и ошибка
его стоит одного лишнего или одного недостающего шага, а не сломанного дела.
"""
from __future__ import annotations

import logging
import re

from . import config, localllm

log = logging.getLogger("justday.dispatch")

TINY = "tiny"
LIGHT = "light"
STRONG = "strong"
BIG = "big"

# Какое усилие какому уровню. Решает тоже не человек: он сказал прямо — «нейросеть должна сама
# решать, какой эффорт, какая модель». «Который час» не становится точнее от высокого усилия, а
# разбор чужой ошибки без него кончается правдоподобной догадкой.
EFFORT = {TINY: "low", LIGHT: "low", STRONG: "medium", BIG: "high"}

# Запасные правила — на случай, когда местной модели нет. Они нарочно грубые: их дело не угадать
# всё, а не ошибиться в очевидном.
_STRONG_WORDS = re.compile(
    r"\b(напиши|перепиши|сверстай|разработай|запрограммируй|отладь|почини|разберись|проанализируй|"
    r"сравни|спланируй|придумай|сочини|переведи|смонтируй|собери|оптимизируй|исследуй|объясни почему|"
    r"code|refactor|debug|analyz|implement)\w*", re.I)
_LONG_ENOUGH = 180          # длинная просьба почти всегда означает непростую
# Работа, а не задача: тут не жалко ни самой сильной модели, ни высокого усилия.
_BIG_WORDS = re.compile(
    r"(с нуля|спроектир\w*|архитектур\w*|переписать (весь|всю|проект)|целиком|"
    r"with scratch|from scratch|rewrite the|architect\w*)", re.I)

_JUDGE_TINY = """Ты распределяешь просьбы между четырьмя моделями ассистента.

КРОШЕЧНАЯ: ответить словом, ничего не делая — который час, какая погода, как дела, что ты умеешь,
короткий пересказ сказанного, «спасибо», «повтори». Ничего открывать, искать и менять не надо.

ЛЁГКАЯ: короткие команды, где всё-таки надо что-то сделать — открыть программу, включить музыку,
громкость, окна, найти файл, посмотреть в интернете.

СИЛЬНАЯ: всё, где надо писать или чинить код, разбирать ошибку, анализировать, сравнивать,
планировать, сочинять длинный текст, монтировать видео, многошаговые задачи с условиями, вопросы
«почему» и «как лучше».

ОГРОМНАЯ: большая работа, а не задача на один присест — спроектировать или написать с нуля,
переписать проект, продумать устройство целиком, сделать сразу много связанных частей, разобраться
в чужом большом коде.

Ответь одним словом: tiny, light, strong или big. Больше ничего не пиши."""

_JUDGE = """Ты распределяешь просьбы между двумя моделями ассистента.

ЛЁГКАЯ: короткие команды и быстрые ответы — открыть программу, включить музыку, громкость, окна,
погода, время, «как дела», поиск файла, простой вопрос с коротким ответом.

СИЛЬНАЯ: всё, где надо писать или чинить код, разбирать ошибку, анализировать, сравнивать,
планировать, сочинять длинный текст, монтировать видео, многошаговые задачи с условиями, вопросы
«почему» и «как лучше».

ОГРОМНАЯ: большая работа, а не задача на один присест — спроектировать или написать с нуля,
переписать проект, продумать устройство целиком, сделать сразу много связанных частей.

Ответь одним словом: light, strong или big. Больше ничего не пиши."""


def level_for(text: str, *, use_model: bool = True, tiny: bool = False) -> tuple[str, str]:
    """Вернуть («tiny»|«light»|«strong», чем решили). Пустая просьба — лёгкая: решать нечего.

    `tiny` включается только тогда, когда крошечной модели есть куда уйти: предлагать уровень,
    которого нет, значит ронять просьбу в пустоту.
    """
    words = (text or "").strip()
    if not words:
        return LIGHT, "пусто"

    if use_model and localllm.available():
        try:
            # Короткий ответ и короткое ожидание: если местная модель задумалась, ждать её дольше
            # секунды бессмысленно — мы экономим время, а не тратим его.
            cfg = (config.load().get("local_llm") or {})
            # Судья отвечает одним словом — и не должен за это слово занимать карту на десять
            # минут: нейронному голосу тогда некуда грузиться, и Джарвис умолкает.
            said = localllm.chat(_JUDGE_TINY if tiny else _JUDGE, words[:2000],
                                 max_tokens=4, timeout=6,
                                 model=str(cfg.get("judge_model") or ""),
                                 keep_alive=str(cfg.get("judge_keep_alive") or "20s")).lower()
            if "big" in said:
                return BIG, "местная модель"
            if "strong" in said:
                return STRONG, "местная модель"
            if tiny and "tiny" in said:
                return TINY, "местная модель"
            if "light" in said:
                return LIGHT, "местная модель"
            log.debug("судья ответил непонятно: %r", said)
        except Exception as e:
            log.debug("местная модель не ответила: %s", type(e).__name__)

    if _BIG_WORDS.search(words):
        return BIG, "по словам"
    if _STRONG_WORDS.search(words) or len(words) >= _LONG_ENOUGH:
        return STRONG, "по словам"
    return LIGHT, "по словам"
