"""Числа вслух: то, на чём синтез речи спотыкается чаще всего.

Ассистент говорит, а не пишет, поэтому «7:05» должно звучать как время, «3,5 ГБ»
— как полтора десятка слов не должно, и род числительного обязан совпадать с
существительным: «две минуты», а не «два минуты».
"""

from __future__ import annotations

import pytest

from justday import numerals


class TestВремяИДлительность:
    @pytest.mark.parametrize("вход,ожидание", [
        ("7:05", "семь ноль пять"),
        ("19:30", "девятнадцать тридцать"),
        ("00:00", "ноль часов"),
    ])
    def test_часы_читаются_как_часы(self, вход: str, ожидание: str) -> None:
        assert numerals.spell(вход) == ожидание

    @pytest.mark.parametrize("секунды,ожидание", [
        (45, "сорок пять секунд"),
        (90, "одна минута тридцать секунд"),
        (3725, "один час две минуты"),
    ])
    def test_длительность_склоняется(self, секунды: int, ожидание: str) -> None:
        assert numerals.duration(секунды) == ожидание


class TestРодИСклонение:
    @pytest.mark.parametrize("вход,ожидание", [
        ("2 минуты", "две минуты"),
        ("1 секунда", "одна секунда"),
        ("2 файла", "два файла"),
        ("21 минута", "двадцать одна минута"),
    ])
    def test_число_согласуется_со_словом(self, вход: str, ожидание: str) -> None:
        assert numerals.spell(вход) == ожидание

    def test_множественное_число_по_правилам(self) -> None:
        формы = ("файл", "файла", "файлов")
        assert numerals.plural(1, формы) == "файл"
        assert numerals.plural(3, формы) == "файла"
        assert numerals.plural(11, формы) == "файлов"
        assert numerals.plural(22, формы) == "файла"


class TestЕдиницыИДроби:
    def test_дробь_с_половиной(self) -> None:
        assert numerals.spell("3,5 ГБ") == "три с половиной гигабайта"

    def test_проценты(self) -> None:
        assert numerals.spell("на 30%") == "на тридцать процентов"

    def test_версия_не_превращается_в_число(self) -> None:
        """«2.1.281» — это версия, а не двести восемьдесят один миллион."""
        assert numerals.spell("версия 2.1.281") == "версия два точка один точка двести восемьдесят один"


class TestЧтоТрогатьНельзя:
    def test_текст_без_чисел_не_меняется(self) -> None:
        фраза = "Музыка играет, всё в порядке"
        assert numerals.spell(фраза) == фраза

    def test_пустая_строка(self) -> None:
        assert numerals.spell("") == ""
